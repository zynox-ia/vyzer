/** Variáveis CSS da paleta (vazio no tema padrão, que usa os tokens do design system). */
export function paletteStyle(palette: CodePalette | undefined) {
  if (!palette) return undefined;
  return {
    "--cs-bg": palette.bg,
    "--cs-fg": palette.fg,
    "--cs-comment": palette.comment,
    "--cs-keyword": palette.keyword,
    "--cs-string": palette.string,
    "--cs-number": palette.number,
    "--cs-type": palette.type,
    "--cs-fn": palette.fn,
    "--cs-add": palette.add,
    "--cs-del": palette.del,
  } as React.CSSProperties;
}
