export type IconEntry = {
  /** Valor salvo. Curados: nome legível ("Bar chart"); demais: nome oficial do lucide ("chart-column"). */
  name: string;
  /** Nome acessível, quando difere do valor salvo. */
  label?: string;
  icon: LucideIcon;
  keywords: string[];
};
export type IconCategory = { title: string; icons: IconEntry[] };

const entry = (name: string, icon: LucideIcon, ...keywords: string[]): IconEntry => ({
  name,
  icon,
  keywords,
});

