/** Todos os ícones, na ordem das categorias. */
export const PROJECT_ICONS: IconEntry[] = ICON_CATEGORIES.flatMap((c) => c.icons);

const kebab = (key: string) =>
  key
    .replace(/([a-z0-9])([A-Z])/g, "$1-$2")
    .replace(/([a-zA-Z])(\d)/g, "$1-$2")
    .toLowerCase();
const humanize = (slug: string) => {
  const text = slug.replaceAll("-", " ");
  return text.charAt(0).toUpperCase() + text.slice(1);
};

let moreIcons: Promise<IconEntry[]> | undefined;

/**
 * Os demais ícones do lucide (fora da curadoria), carregados uma vez, sob demanda, num chunk
 * separado. Ícones já curados (inclusive por apelido) ficam de fora para não repetir.
 */
export function loadMoreIcons(): Promise<IconEntry[]> {
  moreIcons ??= import("./lucide-all").then(({ icons }) => {
    const curated = new Set(PROJECT_ICONS.map((i) => i.icon));
    return Object.entries(icons)
      .filter(([, icon]) => !curated.has(icon))
      .map(([key, icon]) => {
        const name = kebab(key);
        return { name, label: humanize(name), icon, keywords: [] };
      });
  });
  // Se o chunk falhar (rede, asset antigo depois de um deploy), limpa o cache: a próxima
  // abertura tenta de novo em vez de ficar presa na promessa rejeitada.
  moreIcons.catch(() => {
    moreIcons = undefined;
  });
  return moreIcons;
}
